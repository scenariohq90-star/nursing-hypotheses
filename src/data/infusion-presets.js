function createPreset({
  id,
  name,
  category,
  concentrationValue,
  concentrationAmountUnit,
  concentrationUnit,
  calculatorEnabled = true,
  reviewStatus = "source_matched",
  sourcePage,
  flags = [],
}) {
  return Object.freeze({
    id,
    name: Object.freeze(name),
    category: CATEGORIES[category],
    concentrationValue,
    concentrationAmountUnit,
    concentrationUnit,
    calculatorEnabled,
    reviewStatus,
    sourceId: SOURCE_ID,
    sourcePage,
    flags: Object.freeze([...flags]),
  });
}

